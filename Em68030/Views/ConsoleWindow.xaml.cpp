    void ConsoleWindow::OutputBox_KeyDown([[maybe_unused]] IInspectable const& sender,
                                         KeyRoutedEventArgs const& e)
    {
        auto key = e.Key();

        // Ctrl+Shift+F: open search bar (works in all modes)
        {
            auto ctrlState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Control);
            auto shiftState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Shift);
            bool ctrlDown = (ctrlState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                            Windows::UI::Core::CoreVirtualKeyStates::Down;
            bool shiftDown = (shiftState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                             Windows::UI::Core::CoreVirtualKeyStates::Down;
            if (ctrlDown && shiftDown && key == VirtualKey::F)
            {
                OpenSearch();
                e.Handled(true);
                return;
            }
        }

        // Search mode: intercept F3/Shift+F3 and Escape
        if (m_searchMode)
        {
            if (key == VirtualKey::F3)
            {
                auto shiftState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Shift);
                bool shiftDown = (shiftState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                                 Windows::UI::Core::CoreVirtualKeyStates::Down;
                if (shiftDown) FindPrev(); else FindNext();
                e.Handled(true);
                return;
            }
            if (key == VirtualKey::Escape)
            {
                CloseSearch();
                e.Handled(true);
                return;
            }
        }

        if (OnCharInput)
        {
            // MVME147 mode: send VT100 sequences for special keys
            // Arrow keys use ESC O x in application mode (DECCKM), ESC [ x in normal mode
            std::string arrow = m_terminal.GetApplicationCursorKeys() ? "\x1BO" : "\x1B[";
            std::string seq;

            switch (key)
            {
            case VirtualKey::Enter:    seq = "\r"; break;
            case VirtualKey::Up:       seq = arrow + "A"; break;
            case VirtualKey::Down:     seq = arrow + "B"; break;
            case VirtualKey::Left:     seq = arrow + "D"; break;
            case VirtualKey::Right:    seq = arrow + "C"; break;
            case VirtualKey::Home:     seq = "\x1B[H"; break;
            case VirtualKey::End:      seq = "\x1B[F"; break;
            case VirtualKey::Back:     seq = "\x7F"; break;
            case VirtualKey::Delete:   seq = "\x1B[3~"; break;
            case VirtualKey::Tab:      seq = "\t"; break;
            case VirtualKey::Escape:   seq = "\x1B"; break;
            case VirtualKey::PageUp:   seq = "\x1B[5~"; break;
            case VirtualKey::PageDown: seq = "\x1B[6~"; break;
            case VirtualKey::Insert:   seq = "\x1B[2~"; break;
            case VirtualKey::F1:       seq = "\x1BOP"; break;
            case VirtualKey::F2:       seq = "\x1BOQ"; break;
            case VirtualKey::F3:       seq = "\x1BOR"; break;
            case VirtualKey::F4:       seq = "\x1BOS"; break;
            case VirtualKey::F5:       seq = "\x1B[15~"; break;
            case VirtualKey::F6:       seq = "\x1B[17~"; break;
            case VirtualKey::F7:       seq = "\x1B[18~"; break;
            case VirtualKey::F8:       seq = "\x1B[19~"; break;
            case VirtualKey::F9:       seq = "\x1B[20~"; break;
            case VirtualKey::F10:      seq = "\x1B[21~"; break;
            case VirtualKey::F11:      seq = "\x1B[23~"; break;
            case VirtualKey::F12:      seq = "\x1B[24~"; break;
            default: break;
            }

            if (!seq.empty())
            {
                SendRawBytes(seq);
                e.Handled(true);
                return;
            }

            // Ctrl key state (used for Ctrl+C, Ctrl+V, Ctrl+A..Z)
            auto ctrlState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Control);
            bool ctrlDown = (ctrlState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                            Windows::UI::Core::CoreVirtualKeyStates::Down;

            // Ctrl+C: copy selected text, or send 0x03 (ETX) if no selection
            if (ctrlDown && key == VirtualKey::C)
            {
                if (OutputBox().SelectionLength() > 0)
                {
                    Windows::ApplicationModel::DataTransfer::DataPackage dp;
                    dp.SetText(TrimTrailingSpaces(OutputBox().SelectedText()));
                    Windows::ApplicationModel::DataTransfer::Clipboard::SetContent(dp);
                    OutputBox().Select(OutputBox().SelectionStart(), 0);
                }
                else
                {
                    OnCharInput(0x03);
                }
                e.Handled(true);
                return;
            }

            // Ctrl+V: paste clipboard text into SCC
            if (ctrlDown && key == VirtualKey::V)
            {
                PasteFromClipboard(true);
                e.Handled(true);
                return;
            }

            // Ctrl+A..Z -> control codes 0x01..0x1A
            if (ctrlDown && key >= VirtualKey::A && key <= VirtualKey::Z)
            {
                uint8_t code = static_cast<uint8_t>(static_cast<int>(key) - static_cast<int>(VirtualKey::A) + 1);
                OnCharInput(code);
                e.Handled(true);
                return;
            }
        }
        else
        {
            // Ctrl+C: copy selected text
            {
                auto ctrlState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Control);
                bool ctrlDown = (ctrlState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                                Windows::UI::Core::CoreVirtualKeyStates::Down;

                if (ctrlDown && key == VirtualKey::C)
                {
                    if (OutputBox().SelectionLength() > 0)
                    {
                        Windows::ApplicationModel::DataTransfer::DataPackage dp;
                        dp.SetText(TrimTrailingSpaces(OutputBox().SelectedText()));
                        Windows::ApplicationModel::DataTransfer::Clipboard::SetContent(dp);
                        OutputBox().Select(OutputBox().SelectionStart(), 0);
                    }
                    e.Handled(true);
                    return;
                }

                // Ctrl+V: paste clipboard text into input buffer + local echo
                if (ctrlDown && key == VirtualKey::V)
                {
                    PasteFromClipboard(false);
                    e.Handled(true);
                    return;
                }
            }

            // Generic mode: handle special keys for inline input
            switch (key)
            {
            case VirtualKey::Enter:
                SubmitGenericInput();
                e.Handled(true);
                return;
            case VirtualKey::Back:
                if (!m_inputLine.empty())
                {
                    m_inputLine.pop_back();
                    m_terminal.Write("\b \b");
                }
                e.Handled(true);
                return;
            // Suppress keys that would edit the TextBox
            case VirtualKey::Delete:
            case VirtualKey::Home:
            case VirtualKey::End:
            case VirtualKey::Left:
            case VirtualKey::Right:
            case VirtualKey::Up:
            case VirtualKey::Down:
            case VirtualKey::PageUp:
            case VirtualKey::PageDown:
            case VirtualKey::Insert:
            case VirtualKey::Tab:
            case VirtualKey::Escape:
                e.Handled(true);
                return;
            default:
                break;
            }
        }
    }

    void ConsoleWindow::OutputBox_CharacterReceived(
        [[maybe_unused]] UIElement const& sender,
        CharacterReceivedRoutedEventArgs const& e)
    {
        wchar_t wch = e.Character();
        if (wch == 0)
            return;

        // Convert wchar_t to single byte (ASCII range)
        char ch = static_cast<char>(wch & 0x7F);
        // Ignore control characters -- Enter/Tab/Backspace etc. are handled
        // by PreviewKeyDown, so skip CR/LF here to avoid double-sending.
        if (ch < 0x20)
            return;

        if (OnCharInput)
        {
            // MVME147 mode: send each character directly to SCC
            OnCharInput(static_cast<uint8_t>(ch));
        }
        else
        {
            // Generic mode: buffer and locally echo
            m_inputLine += ch;
            m_terminal.Write(ch);
        }

        e.Handled(true);
    }

