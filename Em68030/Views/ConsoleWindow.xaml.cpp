    void ConsoleWindow::SubmitGenericInput()
    {
        std::string text = m_inputLine;
        m_inputLine.clear();

        {
            std::lock_guard lock(m_inputMutex);
            m_lineBuffer.push(text);
            for (char c : text)
                m_charBuffer.push(c);
            m_charBuffer.push('\n');
        }

        m_terminal.Write('\n');
    }

    void ConsoleWindow::OnContextCopy()
    {
        if (OutputBox().SelectionLength() > 0)
        {
            DataPackage dp;
            dp.SetText(TrimTrailingSpaces(OutputBox().SelectedText()));
            Clipboard::SetContent(dp);
        }
    }

    winrt::fire_and_forget ConsoleWindow::PasteFromClipboard(bool rawMode)
    {
        auto content = Clipboard::GetContent();
        if (!content.Contains(StandardDataFormats::Text()))
            co_return;

        auto htext = co_await content.GetTextAsync();
        std::string text = winrt::to_string(htext);

        // Normalize line endings: \r\n -> \r, \n -> \r
        std::string normalized;
        normalized.reserve(text.size());
        for (size_t i = 0; i < text.size(); ++i)
        {
            if (text[i] == '\r' && i + 1 < text.size() && text[i + 1] == '\n')
            {
                normalized += '\r';
                ++i; // skip \n
            }
            else if (text[i] == '\n')
            {
                normalized += '\r';
            }
            else
            {
                normalized += text[i];
            }
        }

        if (rawMode)
        {
            // MVME147 mode: send to SCC
            SendRawBytes(normalized);
        }
        else
        {
            // Generic mode: append to input buffer + local echo
            for (char c : normalized)
            {
                m_inputLine += c;
                m_terminal.Write(c);
            }
        }
    }

    void ConsoleWindow::SendRawBytes(const std::string& data)
    {
        if (!OnCharInput)
            return;
        for (char c : data)
            OnCharInput(static_cast<uint8_t>(c));
    }

