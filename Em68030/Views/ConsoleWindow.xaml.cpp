    void ConsoleWindow::InitConsoleWindow()
    {
        InitializeComponent();
        AppWindow().SetIcon(L"Assets/Em68030.ico");

        // Populate named elements via FindName on the Window's content tree
        if (auto root = Content().try_as<::winrt::Microsoft::UI::Xaml::FrameworkElement>())
        {
            OutputBox(root.FindName(L"OutputBox").try_as<Microsoft::UI::Xaml::Controls::TextBox>());
        }

        // Wire event handlers programmatically (XAML Connect is no-op for C++ native)
        if (OutputBox())
        {
            OutputBox().PreviewKeyDown({ this, &ConsoleWindow::OutputBox_KeyDown });
            OutputBox().CharacterReceived({ this, &ConsoleWindow::OutputBox_CharacterReceived });

            // Custom context menu: Copy, Paste, Select All
            // (IsReadOnly TextBox doesn't show Paste in the default menu)
            auto menuFlyout = Microsoft::UI::Xaml::Controls::MenuFlyout();

            auto copyItem = Microsoft::UI::Xaml::Controls::MenuFlyoutItem();
            copyItem.Text(ResourceHelper::GetString(L"Context_Copy"));
            copyItem.KeyboardAcceleratorTextOverride(L"Ctrl+C");
            copyItem.Click([this](auto&&, auto&&) { OnContextCopy(); });
            menuFlyout.Items().Append(copyItem);

            auto pasteItem = Microsoft::UI::Xaml::Controls::MenuFlyoutItem();
            pasteItem.Text(ResourceHelper::GetString(L"Context_Paste"));
            pasteItem.KeyboardAcceleratorTextOverride(L"Ctrl+V");
            pasteItem.Click([this](auto&&, auto&&) { PasteFromClipboard(OnCharInput != nullptr); });
            menuFlyout.Items().Append(pasteItem);

            auto selectAllItem = Microsoft::UI::Xaml::Controls::MenuFlyoutItem();
            selectAllItem.Text(ResourceHelper::GetString(L"Context_SelectAll"));
            selectAllItem.KeyboardAcceleratorTextOverride(L"Ctrl+A");
            selectAllItem.Click([this](auto&&, auto&&) { OutputBox().SelectAll(); });
            menuFlyout.Items().Append(selectAllItem);

            OutputBox().ContextFlyout(menuFlyout);
        }
        // Focus-follows-mouse: activate window and focus OutputBox when pointer enters
        if (auto root = Content().try_as<::winrt::Microsoft::UI::Xaml::UIElement>())
        {
            root.PointerEntered([this](auto&&, auto&&)
            {
                if (!m_hwnd)
                {
                    auto windowNative = this->try_as<::IWindowNative>();
                    if (windowNative)
                        windowNative->get_WindowHandle(&m_hwnd);
                }
                if (!m_hwnd || ::GetForegroundWindow() == m_hwnd)
                    return;
                // Bypass Windows foreground lock restriction by simulating Alt key
                ::keybd_event(VK_MENU, 0, KEYEVENTF_EXTENDEDKEY, 0);
                ::keybd_event(VK_MENU, 0, KEYEVENTF_EXTENDEDKEY | KEYEVENTF_KEYUP, 0);
                ::SetForegroundWindow(m_hwnd);
                Activate();
                if (OutputBox())
                    OutputBox().Focus(FocusState::Programmatic);
            });
        }

        // Wire search bar buttons
        if (auto root = Content().try_as<::winrt::Microsoft::UI::Xaml::FrameworkElement>())
        {
            if (auto btn = root.FindName(L"SearchNextBtn").try_as<Controls::Button>())
                btn.Click([this](auto&&, auto&&) { FindNext(); });
            if (auto btn = root.FindName(L"SearchPrevBtn").try_as<Controls::Button>())
                btn.Click([this](auto&&, auto&&) { FindPrev(); });
            if (auto btn = root.FindName(L"SearchCloseBtn").try_as<Controls::Button>())
                btn.Click([this](auto&&, auto&&) { CloseSearch(); });
            if (auto box = root.FindName(L"SearchBox").try_as<Controls::TextBox>())
            {
                box.KeyDown([this](auto&&, KeyRoutedEventArgs const& e)
                {
                    if (e.Key() == VirtualKey::Enter)
                    {
                        FindNext();
                        e.Handled(true);
                    }
                    else if (e.Key() == VirtualKey::Escape)
                    {
                        CloseSearch();
                        e.Handled(true);
                    }
                    else if (e.Key() == VirtualKey::F3)
                    {
                        auto shiftState = InputKeyboardSource::GetKeyStateForCurrentThread(VirtualKey::Shift);
                        bool shiftDown = (shiftState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                                         Windows::UI::Core::CoreVirtualKeyStates::Down;
                        if (shiftDown) FindPrev(); else FindNext();
                        e.Handled(true);
                    }
                });
            }
        }

        UpdateTitle();
        AppWindow().Resize({ 700, 510 });

        // Create a DispatcherQueueTimer for 100ms render updates.
        // This is the WinUI 3 equivalent of WPF's DispatcherTimer.
        auto dispatcherQueue = DispatcherQueue();
        m_renderTimer = dispatcherQueue.CreateTimer();
        m_renderTimer.Interval(std::chrono::milliseconds(100));
        m_renderTimerToken = m_renderTimer.Tick([this](auto&&, auto&&)
        {
            RenderScreen();
        });
        m_renderTimer.Start();

        // Focus the output TextBox for keyboard capture
        // Use Loaded event for reliable initial focus (Activated can fire before content is ready)
        if (auto root = Content().try_as<::winrt::Microsoft::UI::Xaml::FrameworkElement>())
        {
            root.Loaded([this](auto&&, auto&&)
            {
                if (OutputBox())
                {
                    OutputBox().Focus(FocusState::Programmatic);
                    MeasureCharCell();
                }
            });

            // SizeChanged for dynamic terminal resize
            root.SizeChanged({ this, &ConsoleWindow::OnSizeChanged });
        }
        // Also re-focus on window re-activation
        Activated([this](auto&&, Microsoft::UI::Xaml::WindowActivatedEventArgs const& args)
        {
            if (args.WindowActivationState() != Microsoft::UI::Xaml::WindowActivationState::Deactivated)
            {
                if (OutputBox())
                    OutputBox().Focus(FocusState::Programmatic);
            }
        });



        // Stop render timer when window is closed (prevents accessing dead UI)
        Closed([this](auto&&, auto&&)
        {
            if (m_renderTimer)
            {
                m_renderTimer.Stop();
                m_renderTimer = nullptr;
            }
        });
    }

