// Trim trailing whitespace from each line of terminal text for clipboard copy
static winrt::hstring TrimTrailingSpaces(winrt::hstring const& text)
{
    std::wstring result;
    result.reserve(text.size());
    size_t lineStart = 0;
    std::wstring_view sv{ text };
    while (lineStart <= sv.size())
    {
        auto pos = sv.find(L'\n', lineStart);
        auto lineEnd = (pos == std::wstring_view::npos) ? sv.size() : pos;
        auto line = sv.substr(lineStart, lineEnd - lineStart);
        // Remove trailing spaces/tabs
        auto trimEnd = line.find_last_not_of(L" \t");
        if (trimEnd != std::wstring_view::npos)
            result.append(line.data(), trimEnd + 1);
        // else: entirely blank line — append nothing (empty line)
        if (pos != std::wstring_view::npos)
            result += L'\n';
        else
            break;
        lineStart = pos + 1;
    }
    return winrt::hstring(result);
}

// Walk the visual tree to find a named child element (for TextBox template parts)
static DependencyObject FindChildByName(DependencyObject const& parent, hstring const& name)
{
    int count = Media::VisualTreeHelper::GetChildrenCount(parent);
    for (int i = 0; i < count; i++)
    {
        auto child = Media::VisualTreeHelper::GetChild(parent, i);
        if (auto fe = child.try_as<FrameworkElement>())
        {
            if (fe.Name() == name)
                return child;
        }
        auto result = FindChildByName(child, name);
        if (result != nullptr)
            return result;
    }
    return nullptr;
}

