    void ConsoleWindow::SetTerminalSize(int cols, int rows)
    {
        cols = std::max(cols, 80);
        rows = std::max(rows, 24);
        if (cols == m_terminal.GetCols() && rows == m_terminal.GetRows()) return;

        m_terminal.Resize(cols, rows);
        UpdateTitle();

        // Adjust window size to fit the new terminal dimensions.
        // AppWindow().Size() is in physical pixels; XAML layout values are in DIPs.
        // Must convert via RasterizationScale to avoid size mismatch at non-100% DPI.
        if (m_charMeasured && m_charWidth > 0 && m_charHeight > 0)
        {
            auto appWindow = AppWindow();
            auto currentSize = appWindow.Size();
            float scale = static_cast<float>(OutputBox().XamlRoot().RasterizationScale());

            float windowWidthDip = static_cast<float>(currentSize.Width) / scale;
            float windowHeightDip = static_cast<float>(currentSize.Height) / scale;

            float textAreaHeight;
            if (m_contentScrollViewer)
                textAreaHeight = static_cast<float>(m_contentScrollViewer.ActualHeight()) - m_textAreaOverhead;
            else
                textAreaHeight = static_cast<float>(OutputBox().ActualHeight()) - 8;
            float textW = static_cast<float>(OutputBox().ActualWidth()) - 8; // Padding="4" x2
            float chromeW = windowWidthDip - textW;
            float chromeH = windowHeightDip - textAreaHeight;

            int newWidth = static_cast<int>((cols * m_charWidth + chromeW) * scale + 0.5f);
            int newHeight = static_cast<int>((rows * m_charHeight + chromeH) * scale + 0.5f);
            appWindow.Resize({ newWidth, newHeight });
        }
    }

    void ConsoleWindow::MeasureCharCell()
    {
        // Measure char width and line step from a multi-line TextBlock.
        // Single-line TextBlock.DesiredSize().Height includes internal top/bottom
        // margins that are NOT repeated per additional line. Using a single-line
        // height as "charHeight" overestimates each line by that margin, causing
        // proportional error: +1 line at 24 rows, +4 lines at 52 rows.
        // Multi-line differencing gives the pure line step.
        auto tb = Microsoft::UI::Xaml::Controls::TextBlock();
        tb.FontFamily(OutputBox().FontFamily());
        tb.FontSize(OutputBox().FontSize());
        tb.TextWrapping(Microsoft::UI::Xaml::TextWrapping::NoWrap);

        const int n1 = 10, n2 = 20;
        constexpr float inf = std::numeric_limits<float>::infinity();
        std::wstring text1, text2;
        for (int i = 0; i < n2; i++)
        {
            if (i > 0) text2 += L'\n';
            text2 += L'M';
            if (i < n1)
            {
                if (i > 0) text1 += L'\n';
                text1 += L'M';
            }
        }

        tb.Text(L"M");
        tb.Measure({ inf, inf });
        m_charWidth = tb.DesiredSize().Width;

        tb.Text(text1);
        tb.Measure({ inf, inf });
        float h10 = tb.DesiredSize().Height;

        tb.Text(text2);
        tb.Measure({ inf, inf });
        float h20 = tb.DesiredSize().Height;

        m_charHeight = (h20 - h10) / static_cast<float>(n2 - n1);

        // Cache the ContentElement (ScrollViewer) inside the TextBox template.
        auto contentObj = FindChildByName(OutputBox(), L"ContentElement");
        m_contentScrollViewer = contentObj.try_as<Controls::ScrollViewer>();

        // Subscribe to ViewChanged for sticky auto-scroll tracking
        if (m_contentScrollViewer)
        {
            m_contentScrollViewer.ViewChanged([this](auto&&, Controls::ScrollViewerViewChangedEventArgs const&)
            {
                if (m_suppressScrollEvent) return;
                double offset = m_contentScrollViewer.VerticalOffset();
                double viewportHeight = m_contentScrollViewer.ViewportHeight();
                double extentHeight = m_contentScrollViewer.ExtentHeight();
                // Threshold: one line height to account for TextWrapping layout changes
                double threshold = m_charHeight > 0 ? m_charHeight : 20;
                bool atBottom = (offset + viewportHeight >= extentHeight - threshold);

                if (m_autoScroll)
                {
                    // Only turn off auto-scroll when user explicitly scrolls away from bottom
                    if (!atBottom)
                        m_autoScroll = false;
                }
                else
                {
                    // Turn auto-scroll back on when user scrolls to the bottom
                    if (atBottom)
                    {
                        m_autoScroll = true;
                        m_terminal.SetDirty();
                    }
                }
            });
        }

        // The overhead is the constant vertical space inside the TextBox content
        // area that isn't text lines (padding, borders, etc.).
        // TextBox Padding="4" → 4 top + 4 bottom = 8 DIPs.
        m_textAreaOverhead = 8;

        // Compute chrome (non-text-area portion of window) in DIPs.
        // AppWindow().Size() is in physical pixels — convert to DIPs via RasterizationScale.
        auto currentSize = AppWindow().Size();
        float scale = static_cast<float>(OutputBox().XamlRoot().RasterizationScale());
        float windowWidthDip = static_cast<float>(currentSize.Width) / scale;
        float windowHeightDip = static_cast<float>(currentSize.Height) / scale;

        float textAreaHeight;
        if (m_contentScrollViewer)
            textAreaHeight = static_cast<float>(m_contentScrollViewer.ActualHeight()) - m_textAreaOverhead;
        else
            textAreaHeight = static_cast<float>(OutputBox().ActualHeight()) - 8;
        float textAreaWidth;
        textAreaWidth = static_cast<float>(OutputBox().ActualWidth()) - 8; // Padding="4" x2
        float chromeW = windowWidthDip - textAreaWidth;
        float chromeH = windowHeightDip - textAreaHeight;

        // WM_GETMINMAXINFO uses physical pixels
        m_minWindowWidth = static_cast<int>((80 * m_charWidth + chromeW) * scale + 0.5f);
        m_minWindowHeight = static_cast<int>((24 * m_charHeight + chromeH) * scale + 0.5f);

        // Install Win32 subclass to handle WM_GETMINMAXINFO for minimum size
        if (!m_hwnd)
        {
            auto windowNative = this->try_as<::IWindowNative>();
            if (windowNative)
            {
                windowNative->get_WindowHandle(&m_hwnd);
                if (m_hwnd)
                    ::SetWindowSubclass(m_hwnd, SubclassProc, 1, reinterpret_cast<DWORD_PTR>(this));
            }
        }

        m_charMeasured = true;

        // Resize window to fit the configured terminal dimensions.
        // The constructor uses a temporary default size; now that we know the
        // actual char cell size, set the correct window size.
        {
            int cols = m_terminal.GetCols();
            int rows = m_terminal.GetRows();
            int newWidth = static_cast<int>((cols * m_charWidth + chromeW) * scale + 0.5f);
            int newHeight = static_cast<int>((rows * m_charHeight + chromeH) * scale + 0.5f);
            AppWindow().Resize({ newWidth, newHeight });
        }
    }

    void ConsoleWindow::UpdateTitle()
    {
        Title(winrt::hstring(ResourceHelper::Format(L"Window_ConsoleFormat",
            m_terminal.GetCols(), m_terminal.GetRows())));
    }

    void ConsoleWindow::OnSizeChanged([[maybe_unused]] IInspectable const& sender,
                                       SizeChangedEventArgs const& /*e*/)
    {
        if (!m_charMeasured || m_charWidth <= 0 || m_charHeight <= 0) return;
        if (!OutputBox()) return;

        // Use the ContentElement (ScrollViewer inside the TextBox) for accurate
        // text area measurement — OutputBox().ActualHeight() includes WinUI3
        // TextBox template chrome (border, header row, etc.) that adds ~3 rows
        // of phantom height. m_textAreaOverhead is measured empirically.
        float availableWidth;
        float availableHeight;
        if (m_contentScrollViewer)
        {
            // Use ScrollViewer viewport for accurate text area (excludes scrollbar)
            availableWidth = static_cast<float>(OutputBox().ActualWidth()) - 8; // Padding="4" x2
            availableHeight = static_cast<float>(m_contentScrollViewer.ActualHeight()) - m_textAreaOverhead;
        }
        else
        {
            availableWidth = static_cast<float>(OutputBox().ActualWidth()) - 8;
            availableHeight = static_cast<float>(OutputBox().ActualHeight()) - 8;
        }

        if (availableWidth <= 0 || availableHeight <= 0) return;

        int newCols = std::max(80, static_cast<int>(availableWidth / m_charWidth));
        int newRows = std::max(24, static_cast<int>(availableHeight / m_charHeight));

        if (newCols != m_terminal.GetCols() || newRows != m_terminal.GetRows())
        {
            m_terminal.Resize(newCols, newRows);
            UpdateTitle();
        }
    }

    // Thread-safe output (called from emulation thread)
    // ========================================================================

    void ConsoleWindow::AppendChar(char ch)
    {
        std::lock_guard lock(m_outputMutex);
        m_outputQueue.push(ch);
    }

    void ConsoleWindow::AppendString(const std::string& s)
    {
        std::lock_guard lock(m_outputMutex);
        for (char ch : s)
            m_outputQueue.push(ch);
    }

    // ========================================================================
    // Thread-safe input (called from emulation thread)
    // ========================================================================

    char ConsoleWindow::ReadChar()
    {
        std::lock_guard lock(m_inputMutex);
        if (!m_charBuffer.empty())
        {
            char ch = m_charBuffer.front();
            m_charBuffer.pop();
            return ch;
        }
        return '\0';
    }

    std::string ConsoleWindow::ReadString()
    {
        std::lock_guard lock(m_inputMutex);
        if (!m_lineBuffer.empty())
        {
            std::string line = m_lineBuffer.front();
            m_lineBuffer.pop();
            return line;
        }
        return "";
    }

    // ========================================================================
    // Render timer callback
    // ========================================================================

    void ConsoleWindow::RenderScreen()
    {
        // Drain output queue into the VT100 terminal emulator.
        // Always drain, even if we skip the UI update, so the terminal
        // state stays current.
        {
            std::lock_guard lock(m_outputMutex);
            while (!m_outputQueue.empty())
            {
                m_terminal.Write(m_outputQueue.front());
                m_outputQueue.pop();
            }
        }

        // Cursor blink: toggle every 5 ticks (500ms on, 500ms off at 100ms interval)
        m_blinkCounter++;
        bool newVisible = (m_blinkCounter / 5) % 2 == 0;
        bool blinkChanged = newVisible != m_cursorVisible;
        m_cursorVisible = newVisible;

        if (!m_terminal.IsDirty() && !blinkChanged)
            return;

        // Suspend text updates while the user has a text selection active,
        // so mouse-drag selections aren't reset every 100ms render tick.
        if (OutputBox().SelectionLength() > 0)
            return;

        // Skip text updates while scrolled back — the terminal continues
        // processing output internally, and will render when user scrolls
        // back to bottom (m_autoScroll becomes true via ViewChanged event).
        if (!m_autoScroll)
        {
            m_terminal.ClearDirty();
            return;
        }

        // Skip if the previous render's UI update hasn't completed yet.
        // The terminal stays dirty so the next timer tick will retry.
        if (m_rendering)
            return;

        m_terminal.ClearDirty();
        m_rendering = true;
        m_suppressScrollEvent = true;

        std::string rendered = m_cursorVisible
            ? m_terminal.RenderFullWithCursor()
            : m_terminal.RenderFull();

        OutputBox().Text(winrt::to_hstring(rendered));

        // Use Select(end, 0) to move caret to end — this works WITH the
        // TextBox's internal "scroll to caret" mechanism to auto-scroll.
        auto textLength = OutputBox().Text().size();
        OutputBox().Select(static_cast<int32_t>(textLength), 0);

        // Clear flags after layout settles (deferred to avoid
        // catching internal scroll events triggered by the text update)
        DispatcherQueue().TryEnqueue(
            Microsoft::UI::Dispatching::DispatcherQueuePriority::Low,
            [this]()
            {
                m_suppressScrollEvent = false;
                m_rendering = false;
            });
    }

