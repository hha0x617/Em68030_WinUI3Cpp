    void SettingsWindow::LoadConfig(const ::Em68030::Config::EmulatorConfig& config)
    {
        // Board type
        SelectItemByText(BoardTypeBox(), config.BoardType);
        Mvme147RomBox().Text(winrt::to_hstring(config.Mvme147RomPath));

        // SCSI Disks
        m_diskRows.clear();
        if (ScsiDiskListPanel())
            ScsiDiskListPanel().Children().Clear();
        for (const auto& disk : config.Mvme147ScsiDisks)
            AddDiskRow(disk.Path, disk.ScsiId);
        if (m_diskRows.empty())
            AddDiskRow("", 0);

        ScsiCdromPathBox().Text(winrt::to_hstring(config.Mvme147ScsiCdromPath));
        m_desiredCdromId = std::clamp(config.Mvme147ScsiCdromId, 0, 6);
        if (BootPartitionBox())
            BootPartitionBox().SelectedIndex(std::clamp(config.Mvme147BootPartition, 0, 1));
        if (TargetOSBox())
            SelectItemByText(TargetOSBox(), config.TargetOS);
        if (LinuxCommandLineBox())
            LinuxCommandLineBox().Text(winrt::to_hstring(config.LinuxCommandLine));
        UpdateTargetOSVisibility();
        if (NetworkModeBox())
            SelectItemByText(NetworkModeBox(), config.NetworkMode);
        if (NatGatewayIpBox())
            NatGatewayIpBox().Text(winrt::to_hstring(config.NatGatewayIp));
        if (NatGatewayMacBox())
            NatGatewayMacBox().Text(winrt::to_hstring(config.NatGatewayMac));
        // Select the saved TAP adapter by GUID
        if (TapAdapterBox() && !config.TapAdapterGuid.empty())
        {
            for (int i = 0; i < static_cast<int>(TapAdapterBox().Items().Size()); i++)
            {
                if (auto item = TapAdapterBox().Items().GetAt(i).try_as<Controls::ComboBoxItem>())
                {
                    auto tag = winrt::unbox_value_or<winrt::hstring>(item.Tag(), L"");
                    if (winrt::to_string(tag) == config.TapAdapterGuid)
                    {
                        TapAdapterBox().SelectedIndex(i);
                        break;
                    }
                }
            }
        }
        UpdateNatGatewayEnabled();
        UpdateMvme147Visibility();
        RefreshScsiIdOptions();

        // Memory
        MemSizeBox().Text(winrt::to_hstring(std::to_string(config.MemorySize / (1024 * 1024))));

        // I/O
        ConsoleEnabledBox().IsChecked(config.ConsoleEnabled);
        {
            wchar_t buf[16];
            swprintf_s(buf, L"%08X", config.ConsoleBaseAddress);
            ConsoleAddrBox().Text(buf);
        }
        ConsoleScrollbackBox().Text(winrt::to_hstring(std::to_string(config.ConsoleScrollbackLines)));
        if (ConsoleColumnsBox())
            ConsoleColumnsBox().Text(winrt::to_hstring(std::to_string(config.ConsoleColumns)));
        if (ConsoleRowsBox())
            ConsoleRowsBox().Text(winrt::to_hstring(std::to_string(config.ConsoleRows)));
        HddEnabledBox().IsChecked(config.HddEnabled);
        {
            wchar_t buf[16];
            swprintf_s(buf, L"%08X", config.HddBaseAddress);
            HddAddrBox().Text(buf);
        }
        HddPathBox().Text(winrt::to_hstring(config.HddImagePath));

        // Framebuffer
        if (FramebufferEnabledBox())
            FramebufferEnabledBox().IsChecked(config.FramebufferEnabled);
        if (FbResolutionBox())
        {
            struct Res { int w, h; };
            static constexpr Res presets[] = {
                {320,240},{640,480},{800,600},{1024,768},{1280,720},{1280,1024},{1920,1080}
            };
            int idx = 1; // default 640x480
            for (int i = 0; i < static_cast<int>(std::size(presets)); i++)
            {
                if (presets[i].w == config.FramebufferWidth && presets[i].h == config.FramebufferHeight)
                { idx = i; break; }
            }
            FbResolutionBox().SelectedIndex(idx);
        }
        if (FbBppBox())
        {
            int bppIndex = (config.FramebufferBpp == 8) ? 0 : (config.FramebufferBpp == 32) ? 2 : 1;
            FbBppBox().SelectedIndex(bppIndex);
        }

        // Performance
        if (JitEnabledBox())
            JitEnabledBox().IsChecked(config.JitEnabled);
        if (JitMinBlockLengthBox())
            JitMinBlockLengthBox().Text(winrt::to_hstring(std::to_string(config.JitMinBlockLength)));
        if (JitCompileThresholdBox())
            JitCompileThresholdBox().Text(winrt::to_hstring(std::to_string(config.JitCompileThreshold)));

        // Debug
        if (EnableTraceButtonBox())
            EnableTraceButtonBox().IsChecked(config.EnableTraceButton);

        // Display
        FontFamilyBox().Text(winrt::to_hstring(config.FontFamily));
        FontSizeBox().Text(winrt::to_hstring(std::to_string(config.FontSize)));
    }

    bool SettingsWindow::SaveConfig(::Em68030::Config::EmulatorConfig& config)
    {
        // Board type
        config.BoardType = GetSelectedItemText(BoardTypeBox());

        config.Mvme147RomPath = winrt::to_string(Mvme147RomBox().Text());

        // SCSI Disks
        config.Mvme147ScsiDisks.clear();
        for (auto& row : m_diskRows)
        {
            std::string path = winrt::to_string(row.PathBox.Text());
            int id = GetSelectedScsiId(row.IdBox);
            if (!path.empty())
                config.Mvme147ScsiDisks.push_back({ path, id });
        }

        config.Mvme147ScsiCdromPath = winrt::to_string(ScsiCdromPathBox().Text());
        config.Mvme147ScsiCdromId = GetSelectedScsiId(ScsiCdromIdBox());
        if (BootPartitionBox())
            config.Mvme147BootPartition = BootPartitionBox().SelectedIndex();
        if (TargetOSBox())
            config.TargetOS = GetSelectedItemText(TargetOSBox());
        if (LinuxCommandLineBox())
            config.LinuxCommandLine = winrt::to_string(LinuxCommandLineBox().Text());
        if (NetworkModeBox())
            config.NetworkMode = GetSelectedItemText(NetworkModeBox());
        if (NatGatewayIpBox())
        {
            auto ip = winrt::to_string(NatGatewayIpBox().Text());
            // Validate: ParseIpAddress returns default on invalid input
            auto parsed = ::Em68030::IO::SlirpNetworkHandler::ParseIpAddress(ip);
            config.NatGatewayIp = std::to_string(parsed[0]) + "." + std::to_string(parsed[1]) + "." +
                                  std::to_string(parsed[2]) + "." + std::to_string(parsed[3]);
        }
        if (NatGatewayMacBox())
        {
            auto mac = winrt::to_string(NatGatewayMacBox().Text());
            auto parsed = ::Em68030::IO::SlirpNetworkHandler::ParseMacAddress(mac);
            char buf[18];
            snprintf(buf, sizeof(buf), "%02x:%02x:%02x:%02x:%02x:%02x",
                     parsed[0], parsed[1], parsed[2], parsed[3], parsed[4], parsed[5]);
            config.NatGatewayMac = buf;
        }
        if (TapAdapterBox() && TapAdapterBox().SelectedItem())
        {
            if (auto item = TapAdapterBox().SelectedItem().try_as<Controls::ComboBoxItem>())
            {
                auto tag = winrt::unbox_value_or<winrt::hstring>(item.Tag(), L"");
                config.TapAdapterGuid = winrt::to_string(tag);
            }
        }

        // Memory size
        auto memText = winrt::to_string(MemSizeBox().Text());
        try {
            int memMB = std::clamp(std::stoi(memText), 4, 4096);
            config.MemorySize = memMB * 1024 * 1024;
        }
        catch (...) { /* keep previous */ }

        // I/O
        config.ConsoleEnabled = ConsoleEnabledBox().IsChecked().Value();
        auto conAddrText = winrt::to_string(ConsoleAddrBox().Text());
        try { config.ConsoleBaseAddress = static_cast<uint32_t>(std::stoul(conAddrText, nullptr, 16)); }
        catch (...) { /* keep previous */ }

        auto scrollbackText = winrt::to_string(ConsoleScrollbackBox().Text());
        try { config.ConsoleScrollbackLines = std::clamp(std::stoi(scrollbackText), 0, 100000); }
        catch (...) { /* keep previous */ }

        if (ConsoleColumnsBox())
        {
            try { config.ConsoleColumns = std::clamp(std::stoi(winrt::to_string(ConsoleColumnsBox().Text())), 80, 320); }
            catch (...) { /* keep previous */ }
        }
        if (ConsoleRowsBox())
        {
            try { config.ConsoleRows = std::clamp(std::stoi(winrt::to_string(ConsoleRowsBox().Text())), 24, 80); }
            catch (...) { /* keep previous */ }
        }

        config.HddEnabled = HddEnabledBox().IsChecked().Value();
        auto hddAddrText = winrt::to_string(HddAddrBox().Text());
        try { config.HddBaseAddress = static_cast<uint32_t>(std::stoul(hddAddrText, nullptr, 16)); }
        catch (...) { /* keep previous */ }

        config.HddImagePath = winrt::to_string(HddPathBox().Text());

        // Framebuffer
        if (FramebufferEnabledBox())
            config.FramebufferEnabled = FramebufferEnabledBox().IsChecked().Value();
        if (FbResolutionBox())
        {
            struct Res { int w, h; };
            static constexpr Res presets[] = {
                {320,240},{640,480},{800,600},{1024,768},{1280,720},{1280,1024},{1920,1080}
            };
            int idx = FbResolutionBox().SelectedIndex();
            if (idx >= 0 && idx < static_cast<int>(std::size(presets)))
            {
                config.FramebufferWidth = presets[idx].w;
                config.FramebufferHeight = presets[idx].h;
            }
        }
        if (FbBppBox())
        {
            auto bppText = GetSelectedItemText(FbBppBox());
            try { config.FramebufferBpp = std::stoi(bppText); }
            catch (...) { /* keep previous */ }
        }

        // Performance
        if (JitEnabledBox())
            config.JitEnabled = JitEnabledBox().IsChecked().Value();
        if (JitMinBlockLengthBox())
        {
            try { config.JitMinBlockLength = std::clamp(std::stoi(winrt::to_string(JitMinBlockLengthBox().Text())), 1, 64); }
            catch (...) { /* keep previous */ }
        }
        if (JitCompileThresholdBox())
        {
            try { config.JitCompileThreshold = std::clamp(std::stoi(winrt::to_string(JitCompileThresholdBox().Text())), 1, 255); }
            catch (...) { /* keep previous */ }
        }

        // Debug
        if (EnableTraceButtonBox())
            config.EnableTraceButton = EnableTraceButtonBox().IsChecked().Value();

        config.FontFamily = winrt::to_string(FontFamilyBox().Text());

        auto fontSizeText = winrt::to_string(FontSizeBox().Text());
        try { config.FontSize = std::stod(fontSizeText); }
        catch (...) { /* keep previous */ }

        // Validate: framebuffer enabled requires enough RAM for kernel (min 32MB usable)
        if (config.FramebufferEnabled)
        {
            constexpr uint32_t MIN_KERNEL_RAM = 32u * 1024 * 1024; // 32MB
            uint32_t vramBase = config.ComputeVramBase();
            if (vramBase < MIN_KERNEL_RAM)
            {
                uint32_t vramSize = static_cast<uint32_t>(config.FramebufferWidth)
                    * config.FramebufferHeight * config.FramebufferBpp / 8;
                int requiredMB = static_cast<int>((MIN_KERNEL_RAM + vramSize + 0xFFFFF) / (1024 * 1024));
                config.MemorySize = requiredMB * 1024 * 1024;
                MemSizeBox().Text(winrt::to_hstring(std::to_string(requiredMB)));
            }
        }

        return true;
    }

    // Recursively walk the visual tree to find a named element
    static DependencyObject FindChildByName(DependencyObject const& parent, hstring const& name)
    {
        int count = Media::VisualTreeHelper::GetChildrenCount(parent);
        for (int i = 0; i < count; i++)
        {
            auto child = Media::VisualTreeHelper::GetChild(parent, i);
            if (auto fe = child.try_as<FrameworkElement>())
            {
                if (fe.Name() == name)
                    return child;
            }
            auto result = FindChildByName(child, name);
            if (result != nullptr)
                return result;
        }
        return nullptr;
    }

    IAsyncOperation<ContentDialogResult> SettingsWindow::ShowAsync(UIElement const& parent)
    {
        this->XamlRoot(parent.XamlRoot());
        auto dialog = this->try_as<ContentDialog>();

        // Override the dialog's internal MaxWidth via the BackgroundElement in the template
        constexpr double dialogWidth = 640.0;
        auto openedToken = dialog.Opened([dialogWidth](ContentDialog const& sender, ContentDialogOpenedEventArgs const&) {
            auto bgElement = FindChildByName(sender, L"BackgroundElement");
            if (auto border = bgElement.try_as<Controls::Border>())
            {
                border.MaxWidth(dialogWidth);
                border.MinWidth(dialogWidth);
            }
            auto layoutRoot = FindChildByName(sender, L"LayoutRoot");
            if (auto grid = layoutRoot.try_as<Controls::Grid>())
            {
                grid.MaxWidth(dialogWidth);
            }
            // Disable the ContentDialog's internal ScrollViewer so that our
            // explicit ScrollViewer receives mouse wheel events directly.
            auto csvElement = FindChildByName(sender, L"ContentScrollViewer");
            if (auto csv = csvElement.try_as<Controls::ScrollViewer>())
            {
                csv.VerticalScrollMode(Controls::ScrollMode::Disabled);
                csv.VerticalScrollBarVisibility(Controls::ScrollBarVisibility::Disabled);
            }
        });

        auto result = co_await dialog.ShowAsync();
        dialog.Opened(openedToken);
        co_return result;
    }

