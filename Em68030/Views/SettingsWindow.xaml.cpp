    HWND SettingsWindow::GetOwnerHwnd() const
    {
        // ContentDialog does not have its own HWND. We need to find the
        // parent Window's HWND via the XamlRoot. In practice, the caller
        // must set XamlRoot before calling ShowAsync, and we walk to find
        // the Window.
        // For file pickers in ContentDialog context, we use the foreground window.
        return ::GetActiveWindow();
    }

    winrt::fire_and_forget SettingsWindow::BrowseFile(winrt::hstring filterName, winrt::hstring filterExt,
                                                       winrt::hstring title,
                                                       TextBox targetBox)
    {
        FileOpenPicker picker;
        picker.as<::IInitializeWithWindow>()->Initialize(GetOwnerHwnd());
        picker.SuggestedStartLocation(PickerLocationId::DocumentsLibrary);
        picker.FileTypeFilter().Append(filterExt);
        picker.FileTypeFilter().Append(L"*");

        auto file = co_await picker.PickSingleFileAsync();
        if (file != nullptr)
        {
            targetBox.Text(file.Path());
        }
    }

    winrt::fire_and_forget SettingsWindow::SaveFile(winrt::hstring filterName, winrt::hstring filterExt,
                                                     winrt::hstring title,
                                                     TextBox targetBox,
                                                     bool isScsiDisk)
    {
        FileSavePicker picker;
        picker.as<::IInitializeWithWindow>()->Initialize(GetOwnerHwnd());
        picker.SuggestedStartLocation(PickerLocationId::DocumentsLibrary);
        picker.FileTypeChoices().Insert(filterName, single_threaded_vector<hstring>({ filterExt }));
        picker.SuggestedFileName(L"disk.img");

        auto file = co_await picker.PickSaveFileAsync();
        if (file == nullptr) co_return;

        auto filePath = winrt::to_string(file.Path());

        int sizeMB = 0;
        try
        {
            if (isScsiDisk)
                sizeMB = std::stoi(winrt::to_string(NewScsiImageSizeBox().Text()));
            else
                sizeMB = std::stoi(winrt::to_string(NewImageSizeBox().Text()));
        }
        catch (...) { co_return; }

        if (sizeMB <= 0) co_return;

        long long sizeBytes = static_cast<long long>(sizeMB) * 1024 * 1024;

        // Create the image file
        if (isScsiDisk)
        {
            // Create empty file and write NetBSD disklabel
            {
                std::ofstream ofs(filePath, std::ios::binary);
                if (ofs)
                {
                    ofs.seekp(sizeBytes - 1);
                    ofs.put('\0');
                }
            }
            // TODO: ScsiDisk::WriteNetBsdDisklabel(filePath);
        }
        else
        {
            ::Em68030::IO::HddDevice::CreateImage(filePath, sizeBytes);
        }

        targetBox.Text(file.Path());
    }

