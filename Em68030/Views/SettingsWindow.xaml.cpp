    void SettingsWindow::CreateScsiImage_Click([[maybe_unused]] IInspectable const& sender,
                                               [[maybe_unused]] RoutedEventArgs const& e)
    {
        // Find or create a target TextBox - use the first empty disk row, or create a new one
        TextBox targetBox{ nullptr };
        for (auto& row : m_diskRows) {
            if (row.PathBox && row.PathBox.Text().empty()) {
                targetBox = row.PathBox;
                break;
            }
        }
        if (!targetBox) {
            AddDiskRow("", 0);
            RefreshScsiIdOptions();
            targetBox = m_diskRows.back().PathBox;
        }
        SaveFile(L"Disk Image", L".img", L"Create SCSI Disk Image", targetBox, true);
    }

