    void SettingsWindow::AddDiskRow(const std::string& path, int scsiId)
    {
        DiskRowState row;
        row.DesiredId = scsiId;

        // ID label
        TextBlock idLabel;
        idLabel.Text(L"ID:");
        idLabel.FontSize(13);
        idLabel.VerticalAlignment(VerticalAlignment::Center);
        idLabel.Margin(ThicknessHelper::FromLengths(0, 0, 4, 0));

        // ID ComboBox - items populated by RefreshScsiIdOptions
        ComboBox idBox;
        idBox.Width(70);
        idBox.VerticalAlignment(VerticalAlignment::Center);
        idBox.Margin(ThicknessHelper::FromLengths(0, 0, 4, 0));
        idBox.SelectionChanged([this]([[maybe_unused]] auto const&, [[maybe_unused]] auto const&) {
            if (!m_refreshingIds) RefreshScsiIdOptions();
        });
        row.IdBox = idBox;

        // Path TextBox
        TextBox pathBox;
        pathBox.Text(winrt::to_hstring(path));
        pathBox.MinWidth(160);
        pathBox.FontFamily(Media::FontFamily(L"Consolas"));
        pathBox.VerticalAlignment(VerticalAlignment::Center);
        row.PathBox = pathBox;

        // Browse button
        Button browseBtn;
        browseBtn.Content(box_value(L"..."));
        browseBtn.Width(30);
        browseBtn.Margin(ThicknessHelper::FromLengths(4, 0, 0, 0));
        browseBtn.VerticalAlignment(VerticalAlignment::Center);
        size_t rowIndex = m_diskRows.size(); // capture current index
        browseBtn.Click([this, pathBox]([[maybe_unused]] auto const&, [[maybe_unused]] auto const&) {
            BrowseFile(L"Disk Image", L".img", L"Select SCSI Disk Image", pathBox);
        });
        row.BrowseBtn = browseBtn;

        // Remove button
        Button removeBtn;
        removeBtn.Content(box_value(L"\u00D7"));
        removeBtn.Width(36);
        removeBtn.Margin(ThicknessHelper::FromLengths(4, 0, 0, 0));
        removeBtn.VerticalAlignment(VerticalAlignment::Center);
        row.RemoveBtn = removeBtn;

        // Row grid (ensures TextBox fills remaining space, buttons always visible)
        Grid grid;
        grid.Margin(ThicknessHelper::FromLengths(0, 2, 0, 2));
        auto colAuto = Controls::ColumnDefinition();
        colAuto.Width(GridLengthHelper::Auto());
        auto colAuto2 = Controls::ColumnDefinition();
        colAuto2.Width(GridLengthHelper::Auto());
        auto colStar = Controls::ColumnDefinition();
        colStar.Width(GridLengthHelper::FromValueAndType(1, GridUnitType::Star));
        auto colAuto3 = Controls::ColumnDefinition();
        colAuto3.Width(GridLengthHelper::Auto());
        auto colAuto4 = Controls::ColumnDefinition();
        colAuto4.Width(GridLengthHelper::Auto());
        grid.ColumnDefinitions().Append(colAuto);
        grid.ColumnDefinitions().Append(colAuto2);
        grid.ColumnDefinitions().Append(colStar);
        grid.ColumnDefinitions().Append(colAuto3);
        grid.ColumnDefinitions().Append(colAuto4);
        Grid::SetColumn(idLabel, 0);
        Grid::SetColumn(idBox, 1);
        Grid::SetColumn(pathBox, 2);
        Grid::SetColumn(browseBtn, 3);
        Grid::SetColumn(removeBtn, 4);
        grid.Children().Append(idLabel);
        grid.Children().Append(idBox);
        grid.Children().Append(pathBox);
        grid.Children().Append(browseBtn);
        grid.Children().Append(removeBtn);
        row.RowPanel = grid;

        m_diskRows.push_back(row);

        // Wire remove button with captured index that finds row by grid identity
        removeBtn.Click([this, grid]([[maybe_unused]] auto const&, [[maybe_unused]] auto const&) {
            for (size_t i = 0; i < m_diskRows.size(); i++) {
                if (m_diskRows[i].RowPanel == grid) {
                    RemoveDiskRow(i);
                    break;
                }
            }
        });

        ScsiDiskListPanel().Children().Append(grid);
    }

    void SettingsWindow::RemoveDiskRow(size_t index)
    {
        if (index >= m_diskRows.size()) return;
        auto panel = m_diskRows[index].RowPanel;
        uint32_t idx = 0;
        if (ScsiDiskListPanel().Children().IndexOf(panel, idx))
            ScsiDiskListPanel().Children().RemoveAt(idx);
        m_diskRows.erase(m_diskRows.begin() + static_cast<ptrdiff_t>(index));
        RefreshScsiIdOptions();
    }

    int SettingsWindow::GetSelectedScsiId(const ComboBox& box) const
    {
        if (box && box.SelectedItem())
        {
            if (auto item = box.SelectedItem().try_as<ComboBoxItem>())
            {
                auto content = item.Content();
                if (content)
                {
                    try { return std::stoi(winrt::to_string(winrt::unbox_value<winrt::hstring>(content))); }
                    catch (...) {}
                }
            }
        }
        return 0;
    }

    void SettingsWindow::RefreshScsiIdOptions()
    {
        if (m_refreshingIds) return;
        m_refreshingIds = true;

        // Collect current IDs for each disk row
        std::vector<int> diskIds(m_diskRows.size());
        for (size_t i = 0; i < m_diskRows.size(); i++)
        {
            auto& row = m_diskRows[i];
            if (row.IdBox && row.IdBox.SelectedItem())
                diskIds[i] = GetSelectedScsiId(row.IdBox);
            else
                diskIds[i] = row.DesiredId;
        }

        int cdromId = (ScsiCdromIdBox() && ScsiCdromIdBox().SelectedItem())
                      ? GetSelectedScsiId(ScsiCdromIdBox())
                      : m_desiredCdromId;

        // Update each disk row's ComboBox
        for (size_t i = 0; i < m_diskRows.size(); i++)
        {
            auto& row = m_diskRows[i];
            int currentId = diskIds[i];

            std::set<int> otherIds;
            for (size_t j = 0; j < m_diskRows.size(); j++) {
                if (j != i) otherIds.insert(diskIds[j]);
            }
            otherIds.insert(cdromId);

            row.IdBox.Items().Clear();
            int selectIndex = 0;
            for (int id = 0; id <= 6; id++)
            {
                if (id != currentId && otherIds.find(id) != otherIds.end())
                    continue;
                ComboBoxItem item;
                item.Content(box_value(winrt::to_hstring(std::to_string(id))));
                row.IdBox.Items().Append(item);
                if (id == currentId)
                    selectIndex = static_cast<int>(row.IdBox.Items().Size()) - 1;
            }
            row.IdBox.SelectedIndex(selectIndex);
            row.DesiredId = currentId;
        }

        // Update CD-ROM ComboBox: exclude disk IDs
        if (ScsiCdromIdBox())
        {
            std::set<int> allDiskIds(diskIds.begin(), diskIds.end());
            int currentCdromId = cdromId;

            ScsiCdromIdBox().Items().Clear();
            int cdromSelectIndex = 0;
            for (int id = 0; id <= 6; id++)
            {
                if (id != currentCdromId && allDiskIds.find(id) != allDiskIds.end())
                    continue;
                ComboBoxItem item;
                item.Content(box_value(winrt::to_hstring(std::to_string(id))));
                ScsiCdromIdBox().Items().Append(item);
                if (id == currentCdromId)
                    cdromSelectIndex = static_cast<int>(ScsiCdromIdBox().Items().Size()) - 1;
            }
            ScsiCdromIdBox().SelectedIndex(cdromSelectIndex);
            m_desiredCdromId = currentCdromId;
        }

        // Update Add button: disable if all IDs taken
        if (AddScsiDiskBtn())
        {
            std::set<int> allUsed(diskIds.begin(), diskIds.end());
            allUsed.insert(cdromId);
            AddScsiDiskBtn().IsEnabled(allUsed.size() < 7);
        }

        m_refreshingIds = false;
    }

