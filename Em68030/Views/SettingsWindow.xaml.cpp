// Helper: get the Content string of the currently selected ComboBoxItem.
static std::string GetSelectedItemText(const Controls::ComboBox& box)
{
    if (!box) return {};
    auto item = box.SelectedItem();
    if (!item) return {};
    if (auto cbi = item.try_as<Controls::ComboBoxItem>())
        return winrt::to_string(cbi.Content().as<winrt::hstring>());
    return {};
}

// Helper: select a ComboBoxItem whose Content matches the given text.
// Falls back to index 0 if no match is found.
static void SelectItemByText(const Controls::ComboBox& box, const std::string& text)
{
    if (!box) return;
    for (int i = 0; i < static_cast<int>(box.Items().Size()); i++)
    {
        if (auto cbi = box.Items().GetAt(i).try_as<Controls::ComboBoxItem>())
        {
            if (winrt::to_string(cbi.Content().as<winrt::hstring>()) == text)
            {
                box.SelectedIndex(i);
                return;
            }
        }
    }
    box.SelectedIndex(0);
}

