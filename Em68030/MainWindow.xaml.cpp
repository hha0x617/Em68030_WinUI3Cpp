    // ========================================================================
    // Button enabled/disabled state management
    // ========================================================================

    void MainWindow::UpdateButtonStates()
    {
        auto vmImpl = m_viewModel.as<implementation::MainViewModel>();
        bool running = vmImpl->IsRunning();
        bool regEdit = vmImpl->IsRegisterEditMode();
        bool memEdit = vmImpl->IsMemoryEditMode();

        // WinUI3's default Button template VisualStateManager overrides
        // Background/Foreground/BorderBrush programmatic changes.
        // Use Opacity (a UIElement property outside the template) to
        // provide a reliable visual distinction for disabled buttons.
        auto setEnabled = [](Controls::Button const& btn, bool enabled) {
            if (!btn) return;
            btn.IsEnabled(enabled);
            btn.Opacity(enabled ? 1.0 : 0.35);
        };

        // Main toolbar buttons
        setEnabled(BtnRun(), !running);
        setEnabled(BtnStop(), running);
        setEnabled(BtnStep(), !running);
        setEnabled(BtnReset(), !running);
        setEnabled(BtnFullReset(), !running);

        // Disassembly controls
        if (auto toggle = BtnFollowPC())
        {
            toggle.IsEnabled(!running);
            toggle.Opacity(!running ? 1.0 : 0.35);
        }

        // Register edit buttons
        setEnabled(BtnEditReg(), !running && !regEdit);
        setEnabled(BtnApplyReg(), regEdit);
        setEnabled(BtnCancelReg(), regEdit);

        // Flag checkboxes (read-only when not in register edit mode)
        for (auto flag : { FlagX(), FlagN(), FlagZ(), FlagV(), FlagC(), FlagS(), FlagT() })
        {
            if (flag) flag.IsEnabled(regEdit);
        }

        // Memory edit buttons
        setEnabled(BtnMemEdit(), !memEdit);
        setEnabled(BtnMemApply(), memEdit);
        setEnabled(BtnMemCancel(), memEdit);
    }

    // ========================================================================
    // Visual tree helper
    // ========================================================================

    template <typename T>
    static T FindVisualChild(Microsoft::UI::Xaml::DependencyObject const& parent)
    {
        int32_t count = Microsoft::UI::Xaml::Media::VisualTreeHelper::GetChildrenCount(parent);
        for (int32_t i = 0; i < count; i++)
        {
            auto child = Microsoft::UI::Xaml::Media::VisualTreeHelper::GetChild(parent, i);
            if (auto result = child.try_as<T>())
                return result;
            auto found = FindVisualChild<T>(child);
            if (found)
                return found;
        }
        return nullptr;
    }

    // ========================================================================
    // Scroll disassembly list to center a given line index
    // ========================================================================

    void MainWindow::ScrollDisasmToCenter(int32_t index)
    {
        if (!DisasmList()) return;
        auto items = DisasmList().Items();
        if (index < 0 || index >= static_cast<int32_t>(items.Size())) return;

        auto sv = FindVisualChild<Microsoft::UI::Xaml::Controls::ScrollViewer>(DisasmList());
        if (!sv) return;

        double itemCount = static_cast<double>(items.Size());
        if (itemCount <= 0) return;
        double itemHeight = sv.ExtentHeight() / itemCount;
        if (itemHeight <= 0) return;

        // Check if the target line is already visible (with 2-line margin)
        double currentTop = sv.VerticalOffset();
        double viewportH = sv.ViewportHeight();
        double targetTop = index * itemHeight;
        double margin = itemHeight * 2;
        if (targetTop >= currentTop + margin && targetTop + itemHeight <= currentTop + viewportH - margin)
            return; // already visible — skip scroll

        // Scroll to center the target line
        double targetOffset = targetTop - viewportH / 2.0 + itemHeight / 2.0;
        if (targetOffset < 0.0) targetOffset = 0.0;
        double scrollableH = sv.ScrollableHeight();
        if (targetOffset > scrollableH) targetOffset = scrollableH;
        sv.ChangeView(nullptr, targetOffset, nullptr);
    }

    // ========================================================================
    // Disassembly list rebuild (programmatic - bypasses XAML data binding)
    // ========================================================================

    void MainWindow::RebuildDisasmList()
    {
        if (!DisasmList()) return;

        auto items = DisasmList().Items();
        items.Clear();

        EnsureDisasmBrushes();
        auto consolasFont = Microsoft::UI::Xaml::Media::FontFamily(L"Consolas");

        auto lines = m_viewModel.DisassemblyLines();
        for (uint32_t i = 0; i < lines.Size(); i++)
        {
            auto line = lines.GetAt(i);
            auto impl = line.as<implementation::DisasmLineViewModel>();

            // Row container: [breakpoint indicator | PC indicator | text]
            Controls::StackPanel row;
            row.Orientation(Controls::Orientation::Horizontal);
            row.Padding(Microsoft::UI::Xaml::ThicknessHelper::FromLengths(2, 0, 2, 0));

            // All rows need an explicit Background for WinUI3 hit-testing,
            // otherwise pointer events (including mouse wheel) pass through.
            row.Background(impl->IsCurrentPC() ? m_brPcBg : m_brTransparent);

            // Breakpoint indicator (red filled circle, gray if disabled)
            Controls::TextBlock bpIndicator;
            bpIndicator.FontFamily(consolasFont);
            bpIndicator.FontSize(13);
            bpIndicator.Width(16);
            bpIndicator.VerticalAlignment(VerticalAlignment::Center);
            if (impl->HasBreakpoint())
            {
                bpIndicator.Text(L"\u25CF"); // filled circle
                bpIndicator.Foreground(impl->HasDisabledBreakpoint() ? m_brGray : m_brRed);
            }

            // Main disassembly text
            Controls::TextBlock mainText;
            mainText.FontFamily(consolasFont);
            mainText.FontSize(13);
            mainText.Text(impl->Text());
            mainText.VerticalAlignment(VerticalAlignment::Center);
            mainText.Margin(Microsoft::UI::Xaml::ThicknessHelper::FromLengths(4, 0, 0, 0));

            if (impl->IsCurrentPC())
                mainText.Foreground(m_brYellow);
            else if (impl->HasDisabledBreakpoint())
                mainText.Foreground(m_brGray);
            else if (impl->HasBreakpoint())
                mainText.Foreground(m_brRed);
            else
                mainText.Foreground(m_brNormal);

            row.Children().Append(bpIndicator);
            row.Children().Append(mainText);
            items.Append(row);
        }
    }

    // ========================================================================
    // Disassembly list in-place appearance update (no flash)
    // ========================================================================

    void MainWindow::EnsureDisasmBrushes()
    {
        if (m_brYellow) return; // already initialized
        m_brYellow = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0xFF, 0xFF, 0xFF, 0x00 });
        m_brRed = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0xFF, 0xFF, 0x00, 0x00 });
        m_brGray = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0xFF, 0x80, 0x80, 0x80 });
        m_brNormal = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0xFF, 0xD4, 0xD4, 0xD4 });
        m_brPcBg = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0xFF, 0x26, 0x4F, 0x78 });
        m_brTransparent = Microsoft::UI::Xaml::Media::SolidColorBrush(
            Windows::UI::Color{ 0x01, 0x00, 0x00, 0x00 });
    }

    void MainWindow::UpdateDisasmListAppearance()
    {
        if (!DisasmList()) return;

        auto items = DisasmList().Items();
        auto lines = m_viewModel.DisassemblyLines();
        if (items.Size() != lines.Size())
        {
            // Item count mismatch — fall back to full rebuild
            RebuildDisasmList();
            return;
        }

        EnsureDisasmBrushes();

        for (uint32_t i = 0; i < lines.Size(); i++)
        {
            auto impl = lines.GetAt(i).as<implementation::DisasmLineViewModel>();
            auto row = items.GetAt(i).as<Controls::StackPanel>();
            if (!row) continue;

            // Determine desired brushes for this row
            auto desiredBg = impl->IsCurrentPC() ? m_brPcBg : m_brTransparent;
            Microsoft::UI::Xaml::Media::SolidColorBrush desiredFg{ nullptr };
            if (impl->IsCurrentPC())
                desiredFg = m_brYellow;
            else if (impl->HasDisabledBreakpoint())
                desiredFg = m_brGray;
            else if (impl->HasBreakpoint())
                desiredFg = m_brRed;
            else
                desiredFg = m_brNormal;

            // Only set Background if the reference changed (avoids WinUI3 re-render)
            if (row.Background() != desiredBg)
                row.Background(desiredBg);

            auto children = row.Children();
            if (children.Size() < 2) continue;

            // Update breakpoint indicator (child 0)
            if (auto bpIndicator = children.GetAt(0).try_as<Controls::TextBlock>())
            {
                if (impl->HasBreakpoint())
                {
                    auto bpBrush = impl->HasDisabledBreakpoint() ? m_brGray : m_brRed;
                    if (bpIndicator.Text().empty())
                        bpIndicator.Text(L"\u25CF");
                    if (bpIndicator.Foreground() != bpBrush)
                        bpIndicator.Foreground(bpBrush);
                }
                else
                {
                    if (!bpIndicator.Text().empty())
                        bpIndicator.Text(L"");
                }
            }

            // Update text color (child 1) — only if reference changed
            if (auto mainText = children.GetAt(1).try_as<Controls::TextBlock>())
            {
                if (mainText.Foreground() != desiredFg)
                    mainText.Foreground(desiredFg);
            }
        }
    }

    // ========================================================================
    // Console window
    // ========================================================================

    void MainWindow::EnsureConsoleWindow()
    {
        if (!m_consoleWindow)
        {
            auto vmImpl = m_viewModel.as<implementation::MainViewModel>();
            auto& cfg = vmImpl->Config();
            m_consoleWindow = winrt::make<implementation::ConsoleWindow>(
                cfg.ConsoleColumns, cfg.ConsoleRows, cfg.ConsoleScrollbackLines);

            // In MVME147 mode, wire raw character input so keyboard input goes
            // directly to the SCC device via ViewModel::SendConsoleChar.
            // In Generic mode, leave OnCharInput unset so input goes through
            // line-buffered ReadChar/ReadString callbacks instead.
            if (vmImpl->Config().BoardType == "MVME147")
            {
                auto consoleImpl = m_consoleWindow.as<implementation::ConsoleWindow>();
                consoleImpl->OnCharInput = [vmImpl](uint8_t ch) {
                    vmImpl->SendConsoleChar(ch);
                };
            }

            // Clear reference when the console window is closed so we can
            // create a fresh one next time.
            m_consoleWindow.Closed([this](auto&&, auto&&)
            {
                m_consoleWindow = nullptr;
            });
        }
        m_consoleWindow.Activate();
        SetOwnerWindow(m_consoleWindow, *this);
    }

    // ========================================================================
    // Framebuffer window
    // ========================================================================

    void MainWindow::ReopenFramebufferWindow()
    {
        if (!m_framebufferWindow) return;

        // Save position before closing
        auto appWindow = m_framebufferWindow.AppWindow();
        auto pos = appWindow.Position();

        m_framebufferWindow.Close();
        m_framebufferWindow = nullptr;

        EnsureFramebufferWindow();

        // Restore position
        if (m_framebufferWindow)
            m_framebufferWindow.AppWindow().Move(pos);
    }

    void MainWindow::EnsureFramebufferWindow()
    {
        auto vmImpl = m_viewModel.as<implementation::MainViewModel>();
        auto* fbDevice = vmImpl->FramebufferDevice();
        if (!fbDevice) return;

        if (!m_framebufferWindow)
        {
            m_framebufferWindow = winrt::make<implementation::FramebufferWindow>();
            auto fbImpl = m_framebufferWindow.as<implementation::FramebufferWindow>();
            fbImpl->Init(vmImpl->Memory(), *fbDevice, vmImpl->InputDevice());

            m_framebufferWindow.Closed([this](auto&&, auto&&)
            {
                m_framebufferWindow = nullptr;
            });
        }
        m_framebufferWindow.Activate();
        SetOwnerWindow(m_framebufferWindow, *this);
    }

    // ========================================================================
    // Breakpoints window
    // ========================================================================

    void MainWindow::EnsureBreakpointsWindow()
    {
        if (!m_breakpointsWindow)
        {
            m_breakpointsWindow = winrt::make<implementation::BreakpointsWindow>();
            auto bpImpl = m_breakpointsWindow.as<implementation::BreakpointsWindow>();
            auto vmImpl = m_viewModel.as<implementation::MainViewModel>();

            bpImpl->OnToggleEnabled = [this, vmImpl](uint32_t addr, bool enabled)
            {
                vmImpl->EnableBreakpoint(addr, enabled);
                UpdateDisasmListAppearance();
                RefreshBreakpointsWindow();
            };
            bpImpl->OnDelete = [this, vmImpl](uint32_t addr)
            {
                vmImpl->RemoveBreakpoint(addr);
                UpdateDisasmListAppearance();
                RefreshBreakpointsWindow();
            };
            bpImpl->OnClearAll = [this, vmImpl]()
            {
                vmImpl->ClearAllBreakpoints();
                UpdateDisasmListAppearance();
                RefreshBreakpointsWindow();
            };
            bpImpl->OnDoubleClick = [this, vmImpl](uint32_t addr)
            {
                // 1) Update data model (may re-disassemble around the address)
                vmImpl->ScrollToAddress(addr);
                // 2) Rebuild UI from updated data
                RebuildDisasmList();
                // 3) Find the target line and scroll to center
                auto lines = vmImpl->DisassemblyLines();
                for (uint32_t i = 0; i < lines.Size(); i++)
                {
                    auto lineImpl = lines.GetAt(i).as<implementation::DisasmLineViewModel>();
                    if (lineImpl->HasAddress() && lineImpl->Address() == addr)
                    {
                        ScrollDisasmToCenter(static_cast<int32_t>(i));
                        break;
                    }
                }
            };

            m_breakpointsWindow.Closed([this](auto&&, auto&&)
            {
                m_breakpointsWindow = nullptr;
            });
        }
        m_breakpointsWindow.Activate();
        SetOwnerWindow(m_breakpointsWindow, *this);
        RefreshBreakpointsWindow();
    }

    void MainWindow::RefreshBreakpointsWindow()
    {
        if (!m_breakpointsWindow) return;
        auto bpImpl = m_breakpointsWindow.as<implementation::BreakpointsWindow>();
        auto vmImpl = m_viewModel.as<implementation::MainViewModel>();
        bpImpl->RefreshList(vmImpl->AllBreakpoints());
    }

    // ========================================================================
    // Helper: get address of selected disasm line
    // ========================================================================

    uint32_t MainWindow::GetSelectedDisasmAddress()
    {
        if (!DisasmList()) return 0xFFFFFFFF;
        int32_t idx = DisasmList().SelectedIndex();
        if (idx < 0) return 0xFFFFFFFF;

        // Map selection index to ViewModel's DisassemblyLines collection
        auto lines = m_viewModel.DisassemblyLines();
        if (static_cast<uint32_t>(idx) >= lines.Size()) return 0xFFFFFFFF;

        auto line = lines.GetAt(static_cast<uint32_t>(idx));
        auto impl = line.as<implementation::DisasmLineViewModel>();
        if (impl->HasAddress())
            return impl->Address();
        return 0xFFFFFFFF;
    }

