    void MainWindow::CopyDisasmSelection()
    {
        if (!DisasmList()) return;
        auto selectedItems = DisasmList().SelectedItems();
        if (selectedItems.Size() == 0) return;

        std::wstring combined;
        for (uint32_t i = 0; i < selectedItems.Size(); ++i)
        {
            if (i > 0) combined += L"\r\n";
            auto item = selectedItems.GetAt(i);
            // Items are StackPanel rows: [bpIndicator, pcIndicator, mainText]
            if (auto sp = item.try_as<Controls::StackPanel>())
            {
                if (sp.Children().Size() >= 3)
                {
                    if (auto tb = sp.Children().GetAt(2).try_as<Controls::TextBlock>())
                        combined += std::wstring(tb.Text());
                }
            }
        }

        if (!combined.empty())
        {
            DataPackage dataPackage;
            dataPackage.SetText(combined);
            Clipboard::SetContent(dataPackage);
        }
    }

