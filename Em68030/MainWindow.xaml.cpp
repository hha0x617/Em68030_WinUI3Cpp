    void MainWindow::DisasmList_KeyDown([[maybe_unused]] IInspectable const& sender,
                                        KeyRoutedEventArgs const& e)
    {
        auto ctrlState = Microsoft::UI::Input::InputKeyboardSource::GetKeyStateForCurrentThread(
            winrt::Windows::System::VirtualKey::Control);
        bool ctrlDown = (ctrlState & Windows::UI::Core::CoreVirtualKeyStates::Down) ==
                        Windows::UI::Core::CoreVirtualKeyStates::Down;

        if (e.Key() == Windows::System::VirtualKey::C && ctrlDown)
        {
            CopyDisasmSelection();
            e.Handled(true);
        }
    }

    void MainWindow::DisasmList_RightTapped([[maybe_unused]] IInspectable const& sender,
                                            RightTappedRoutedEventArgs const& e)
    {
        // Select the item under the pointer so context menu actions work correctly
        if (!DisasmList()) return;
        auto position = e.GetPosition(DisasmList());
        auto items = DisasmList().Items();
        for (uint32_t i = 0; i < items.Size(); i++)
        {
            auto container = DisasmList().ContainerFromIndex(static_cast<int>(i));
            if (!container) continue;
            auto element = container.try_as<Microsoft::UI::Xaml::UIElement>();
            if (!element) continue;

            auto transform = element.TransformToVisual(DisasmList());
            auto topLeft = transform.TransformPoint({ 0, 0 });
            auto fe = element.try_as<Microsoft::UI::Xaml::FrameworkElement>();
            if (!fe) continue;

            if (position.Y >= topLeft.Y && position.Y < topLeft.Y + fe.ActualHeight())
            {
                DisasmList().SelectedIndex(static_cast<int>(i));
                break;
            }
        }
    }

